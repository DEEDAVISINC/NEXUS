# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _now_date() -> str:
    return datetime.now().date().isoformat()


def _due_date(days: int = 30) -> str:
    return (datetime.now().date() + timedelta(days=days)).isoformat()


def _inv_number(prefix: str = "INV") -> str:
    return f"{prefix}-{datetime.now().strftime('%Y%m%d-%H%M%S')}"


def _log_to_vertex_reports(
    event_type: str,
    source_system: str,
    source_record_id: str,
    outcome: str,
    detail: str,
    airtable=None,
):
    """Write an audit entry to VERTEX REPORTS."""
    try:
        at = airtable or _airtable()
        at.create_record("VERTEX REPORTS", {
            "REPORT DATE":     _now_date(),
            "REPORT TYPE":     "Auto-Trigger Event",
            "SOURCE SYSTEM":   source_system,
            "SOURCE RECORD":   source_record_id,
            "EVENT TYPE":      event_type,
            "OUTCOME":         outcome,
            "DETAILS":         detail[:5000],
            "GENERATED BY":    "vertex_automation.py",
        })
    except Exception as ex:
        log.warning(f"Could not write to VERTEX REPORTS: {ex}")


