#!/usr/bin/env python3
"""
vertex_automation.py — VERTEX Auto-Trigger Layer

Every NEXUS module fires VERTEX actions automatically on key events.
No manual invoice or revenue record creation needed.

Event API:
    from vertex_automation import vertex_auto_trigger
    vertex_auto_trigger('gpss.opportunity.won', source_record_id='recXXX', data={...})

All triggers are logged to VERTEX REPORTS for audit trail.

Event types:
    gpss.opportunity.won          → Invoice schedule + AP records + WAWF if federal
    gpss.opportunity.lost         → Cancel draft invoices
    atlas.milestone.complete      → Milestone invoice
    atlas.expense.logged          → VERTEX EXPENSE record
    prism.service.complete        → Service invoice from rate table
    prism.drug_test.collected     → Queue test invoice (batch daily)
    ddcss.client.won              → Consulting/service invoice
    compass.qa.passed             → Release held invoice
    compass.qa.failed             → Flag + hold invoice
    gbis.grant.awarded            → Revenue record + expense tracking setup
    lbpc.recovery.complete        → Contingency fee invoice (30%)
    nemt.trip.complete            → Delegated to nemt_billing.generate_claim()
    fleetflow.delivery.confirmed  → Freight/logistics invoice
    shield.service.verified       → SHIELD service invoice (Medicaid CHW billing)
    shield.time.verified          → Navigator time-based invoice (15-min units)
    shield.billing.approved       → Move invoice Pending Approval → Ready to Submit
"""

