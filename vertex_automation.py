def _handle_gpss_opportunity_won(source_record_id: str, data: Dict, at) -> Dict:
    """
    Contract won:
    - Create a client invoice (or recurring template for service contracts)
    - Create AP record for each sub if sub cost is provided
    - Mark WAWF required if federal
    """
    VI = _vi(); VR = _vr(); VAP = _vap()

    agency        = data.get("agency_name", "")
    title         = data.get("title", "")
    value         = float(data.get("contract_value", 0) or 0)
    contract_num  = data.get("contract_number", "")
    is_federal    = data.get("is_federal", False)
    is_service    = data.get("is_service_contract", False)
    sub_cost      = float(data.get("sub_cost", 0) or 0)
    sub_name      = data.get("sub_name", "")
    payment_terms = data.get("payment_terms", "Net 30")

    created = {}

    if value > 0:
        inv_fields = {
            VI["invoice_number"]:  _inv_number("INV"),
            VI["invoice_date"]:    _now_date(),
            VI["due_date"]:        _due_date(30),
            VI["client_name"]:     agency,
            VI["source_system"]:   "GPSS",
            VI["source_record"]:   source_record_id,
            VI["invoice_type"]:    "Service Contract" if is_service else "Standard",
            VI["total_amount"]:    value,
            VI["payment_status"]:  "Unpaid",
            VI["payment_terms"]:   payment_terms,
            VI["notes"]:           f"Auto-generated on contract award: {title}",
            VI["contract_number"]: contract_num,
            VI["government_agency"]: agency,
        }
        if is_service:
            from api_server import VI_RECURRING, _FREQ_DAYS
            inv_fields[VI_RECURRING["recurring"]]           = True
            inv_fields[VI_RECURRING["recurring_frequency"]] = "Monthly"
            inv_fields[VI_RECURRING["next_invoice_date"]]   = _due_date(30)
        if is_federal:
            inv_fields[VI.get("wawf_status", "WAWF STATUS")] = "Not Submitted"

        invoice = at.create_record("VERTEX INVOICES", inv_fields)
        created["invoice"] = invoice.get("id")
        log.info(f"[GPSS Won] Invoice created: {invoice.get('id')} for ${value:,.2f}")

    # AP record for sub if sub cost provided
    if sub_cost > 0 and sub_name:
        ap_fields = {
            VAP["bill_number"]:    _inv_number("AP"),
            VAP["bill_date"]:      _now_date(),
            VAP["due_date"]:       _due_date(30),
            VAP["vendor_name"]:    sub_name,
            VAP["source_system"]:  "GPSS",
            VAP["source_record"]:  source_record_id,
            VAP["category"]:       "Sub Labor",
            VAP["description"]:    f"Subcontractor cost for: {title}",
            VAP["total_amount"]:   sub_cost,
            VAP["payment_status"]: "Unpaid",
            VAP["payment_terms"]:  "Net 30",
            VAP["contract_number"]: contract_num,
        }
        ap = at.create_record("VERTEX ACCOUNTS PAYABLE", ap_fields)
        created["ap_bill"] = ap.get("id")
        log.info(f"[GPSS Won] AP bill created: {ap.get('id')} for sub ${sub_cost:,.2f}")

    return created


def _handle_gpss_opportunity_lost(source_record_id: str, data: Dict, at) -> Dict:
    """Cancel any Unpaid invoices tied to this opportunity."""
    VI = _vi()
    formula = f"AND({{{VI['source_record']}}}='{source_record_id}',{{{VI['payment_status']}}}='Unpaid')"
    try:
        invoices = at.search_records("VERTEX INVOICES", formula)
        cancelled = []
        for inv in invoices:
            at.update_record("VERTEX INVOICES", inv["id"], {
                VI["payment_status"]: "Cancelled",
                VI["notes"]: (inv.get("fields", {}).get(VI["notes"], "") or "") + " | Auto-cancelled: opportunity lost",
            })
            cancelled.append(inv["id"])
        log.info(f"[GPSS Lost] Cancelled {len(cancelled)} draft invoices")
        return {"cancelled_invoices": cancelled}
    except Exception as e:
        log.error(f"[GPSS Lost] Error cancelling invoices: {e}")
        return {"error": str(e)}


