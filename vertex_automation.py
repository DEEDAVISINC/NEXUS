def vertex_auto_trigger(
    event_type: str,
    source_record_id: str = "",
    data: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Main entry point for all VERTEX auto-triggers.

    Args:
        event_type:       One of the defined event strings (e.g. 'gpss.opportunity.won')
        source_record_id: The Airtable record ID of the triggering entity
        data:             Dict with event-specific fields (agency_name, amount, etc.)

    Returns:
        Dict with outcome details, suitable for logging or returning from an API endpoint.
    """
    data = data or {}
    handler = _EVENT_HANDLERS.get(event_type)
    at = _airtable()

    if not handler:
        log.warning(f"vertex_auto_trigger: unknown event_type '{event_type}'")
        return {"error": f"Unknown event type: {event_type}"}

    source_system = event_type.split(".")[0].upper()
    try:
        result = handler(source_record_id, data, at)
        outcome = "success"
        detail  = json.dumps(result, default=str)
        log.info(f"vertex_auto_trigger OK: {event_type} → {detail[:200]}")
    except Exception as e:
        result  = {"error": str(e)}
        outcome = "error"
        detail  = str(e)
        log.error(f"vertex_auto_trigger FAILED: {event_type} — {e}")

    _log_to_vertex_reports(event_type, source_system, source_record_id, outcome, detail, at)
    return {
        "event_type":       event_type,
        "source_record_id": source_record_id,
        "outcome":          outcome,
        "result":           result,
    }
