def _jdoc_keys(canonical: str) -> tuple:
    leg = _LEGACY.get(canonical, ())
    return (canonical,) + leg


def jdoc_get_raw(f: dict, canonical: str) -> Any:
    for k in _jdoc_keys(canonical):
        if k in f:
            return f.get(k)
    return None


def jdoc_get_str(f: dict, canonical: str) -> str:
    for k in _jdoc_keys(canonical):
        if k not in f:
            continue
        v = f[k]
        if v is None:
            continue
        if isinstance(v, (int, float)):
            s = str(int(v) if isinstance(v, float) and v == int(v) else v)
        else:
            s = str(v).strip()
        if s == '':
            continue
        return s
    return ''


def jdoc_get_float(f: dict, canonical: str) -> Optional[float]:
    for k in _jdoc_keys(canonical):
        if k not in f or f[k] is None or f[k] == '':
            continue
        try:
            return float(f[k])
        except (TypeError, ValueError):
            continue
    return None


def jdoc_get_bool(f: dict, canonical: str) -> Optional[bool]:
    for k in _jdoc_keys(canonical):
        if k not in f or f[k] is None:
            continue
        v = f[k]
        if isinstance(v, bool):
            return v
        if isinstance(v, (int, float)):
            return bool(v)
        s = str(v).strip().lower()
        if s in ('yes', 'true', '1', 'y'):
            return True
        if s in ('no', 'false', '0', 'n'):
            return False
    return None


def jdoc_link_ids(f: dict, canonical: str) -> List[str]:
    raw = jdoc_get_raw(f, canonical)
    if raw is None:
        return []
    if isinstance(raw, list):
        return [str(x) for x in raw if x]
    return []


def jdoc_first_link_id(f: dict, canonical: str) -> str:
    ids = jdoc_link_ids(f, canonical)
    return ids[0] if ids else ''


def jdoc_pdf_path_local(f: dict) -> str:
    """Legacy local filename under GENERATED_JETA_DOCUMENTS."""
    return str(f.get('PDF Path') or '').strip()
