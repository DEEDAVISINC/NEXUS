    sent_date = 'sent_date'
    sent_to = 'sent_to'
    signed_status = 'signed_status'
    signed_date = 'signed_date'
    expiry_date = 'expiry_date'
    pdf_link = 'pdf_link'
    notes = 'notes'
    escalation_clause_version = 'escalation_clause_version'


